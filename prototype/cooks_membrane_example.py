"""Run prototype Cook's membrane and save explicitly labelled PNG/VTK/CSV files.

    python -B -m prototype.cooks_membrane_example
    python -B -m prototype.cooks_membrane_example --levels 0 1 2 --steps 4

Level l uses h=4/2**l mm Cartesian staircase cells. Defaults run four levels
(h=4,2,1,0.5 mm), one load step each, matching the linear-elastic OGS problem.
The sloped geometry is approximated; the conforming OGS reference is supplied
for comparison and is not generated by this runner.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from prototype.cooks_membrane import make_case, run_case
from prototype.cooks_membrane_plots import export_results


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--levels", type=int, nargs="+", default=[0, 1, 2, 3])
    parser.add_argument("--steps", type=int, default=1)
    parser.add_argument("--output-dir", type=Path, default=Path("results/prototype_cooks_membrane"))
    args = parser.parse_args()
    results = []
    for level in sorted(set(args.levels)):
        print(f"Preparing prototype Cook's membrane, refinement level {level}", flush=True)
        results.append(run_case(make_case(level), steps=args.steps, progress=True))
    paths = export_results(results, args.output_dir)
    print(f"Prototype outputs: {args.output_dir}")
    print(f"Settings, approximation and numerical checks: {paths['summary']}")


if __name__ == "__main__":
    main()
